#!/usr/bin/env sh
set -eu

failed=0
images=$(docker compose --profile '*' config --images)
for image in $images; do
  case "$image" in
    greenroute/*:0.1.0-local) ;;
    *@sha256:????????????????????????????????????????????????????????????????) ;;
    *) echo "external Compose image is not digest-pinned: $image" >&2; failed=1 ;;
  esac
  case "$image" in
    *:latest|latest) echo "latest tag is forbidden: $image" >&2; failed=1 ;;
  esac
done

dockerfiles=$(find . -type f \( -name Dockerfile -o -name '*.Dockerfile' \) \
  -not -path './.git/*' -not -path './apps/web/node_modules/*' -not -path './apps/web/.next/*')
for dockerfile in $dockerfiles; do
  while IFS= read -r base; do
    case "$base" in
      scratch|*@sha256:????????????????????????????????????????????????????????????????) ;;
      *) echo "external Dockerfile base is not digest-pinned: $dockerfile: $base" >&2; failed=1 ;;
    esac
  done <<EOF
$(awk 'toupper($1) == "FROM" { if ($2 ~ /^--platform=/) print $3; else print $2 }' "$dockerfile")
EOF
done
exit "$failed"
